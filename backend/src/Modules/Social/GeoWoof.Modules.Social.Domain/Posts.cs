/// <summary>
/// One person shows the post of another on their profile. It points to the original and does not copy
/// it: only those who can see the original see the repost, and it goes away with the original.
/// </summary>
public sealed class Repost : AggregateRoot
{
    /// <summary>Constructor for EF Core.</summary>
    private Repost()
    {
    }

    private Repost(Guid id, Guid postId, Guid userId, DateTimeOffset now)
        : base(id)
    {
        PostId = postId;
        UserId = userId;
        CreatedAt = now;
    }

    public Guid PostId { get; private set; }

    public Guid UserId { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public static Repost Create(Guid id, Post post, Guid userId, DateTimeOffset now)
    {
        var repost = new Repost(id, post.Id, userId, now);
        repost.Raise(new PostRepostedDomainEvent(id, post.Id, post.AuthorId, userId));
        return repost;
    }
}

