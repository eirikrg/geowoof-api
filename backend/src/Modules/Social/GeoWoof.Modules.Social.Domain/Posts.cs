/// <summary>A mention that counts: the account exists, and that person can see what was written.</summary>
public sealed record Mention(Guid UserId, string Username);

/// <summary>Finds the <c>@usernames</c> of a text. Whether each one is a real mention is decided later.</summary>
public static partial class MentionParser
{
    public const int MaxMentions = 10;

    /// <returns>Lower-cased, without repeating any, in the order they appear.</returns>
    public static IReadOnlyList<string> Parse(string? text) =>
        string.IsNullOrEmpty(text)
            ? []
            : Pattern().Matches(text)
                .Select(match => match.Groups[1].Value.TrimEnd('.').ToLowerInvariant())
                .Distinct(StringComparer.Ordinal)
                .Take(MaxMentions)
                .ToList();

    /// <summary>An email is not a mention, so it cannot come right after a letter, a digit or a dot.</summary>
    [GeneratedRegex(@"(?<![\p{L}\p{N}_.@])@([A-Za-z][A-Za-z0-9_.]{2,29})(?![A-Za-z0-9_])", RegexOptions.CultureInvariant)]
    private static partial Regex Pattern();
}

/// <summary>Photos with a text, shown to who the author chooses. Uploading a photo to the profile is creating one.</summary>
public sealed class Post : AggregateRoot
{
    public const int TextMaxLength = 2000;
    public const int MaxMedia = 10;
    public const int MaxPets = 10;

    private readonly List<PostMedia> _media = [];
    private readonly List<PostPet> _pets = [];
    private readonly List<PostMention> _mentions = [];

    /// <summary>Constructor for EF Core.</summary>
    private Post()
    {
    }

    private Post(Guid id, Guid authorId, string? text, ContentVisibility visibility, bool authorIsPrivate, DateTimeOffset now)
        : base(id)
    {
        AuthorId = authorId;
        Text = string.IsNullOrWhiteSpace(text) ? null : text.Trim();
        Visibility = visibility;
        AuthorIsPrivate = authorIsPrivate;
        CreatedAt = now;
    }

    public Guid AuthorId { get; private set; }

    public string? Text { get; private set; }

    public ContentVisibility Visibility { get; private set; }

    /// <summary>
    /// A copy of what the Identity module says, so that a query can filter by it. It is updated by an
    /// event, so the rules are applied again with the current value when the post is shown.
    /// </summary>
    public bool AuthorIsPrivate { get; private set; }

    public DateTimeOffset CreatedAt { get; private set; }

    public IReadOnlyList<PostMedia> Media => _media;

    public IReadOnlyList<PostPet> Pets => _pets;

    public IReadOnlyList<PostMention> Mentions => _mentions;

    /// <param name="id">Generated by the app, so that repeating the request does not create another.</param>
    /// <param name="authorId">Who publishes it.</param>
    /// <param name="text">Optional.</param>
    /// <param name="visibility">Who can see it.</param>
    /// <param name="authorIsPrivate">Whether the profile of the author is private now.</param>
    /// <param name="assetIds">The images, in the order they are shown.</param>
    /// <param name="petIds">The pets of the author that appear in it.</param>
    /// <param name="found">The mentions that count.</param>
    /// <param name="now">The current time.</param>
    public static Post Create(
        Guid id,
        Guid authorId,
        string? text,
        ContentVisibility visibility,
        bool authorIsPrivate,
        IReadOnlyList<Guid> assetIds,
        IReadOnlyCollection<Guid> petIds,
        IReadOnlyCollection<Mention> found,
        DateTimeOffset now)
    {
        var post = new Post(id, authorId, text, visibility, authorIsPrivate, now);
        post._media.AddRange(assetIds.Select((assetId, position) => new PostMedia(id, position, PostMediaType.Image, assetId)));
        post._pets.AddRange(petIds.Select(petId => new PostPet(id, petId)));
        post._mentions.AddRange(found.Select(mention => new PostMention(id, mention.UserId, mention.Username)));
        post.Raise(new PostCreatedDomainEvent(id, authorId, visibility));
        foreach (var mention in found.Where(mention => mention.UserId != authorId))
        {
            post.Raise(new UserMentionedDomainEvent(mention.UserId, authorId, id, CommentId: null));
        }

        return post;
    }
}

